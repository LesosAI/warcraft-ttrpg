/**
 * Migration to 0.16.1.1 - the 2026-11 bestiary audit on the creatures a world already holds
 * (D-1801 to D-1803; the lead, 2026-11-22: *"migration to update existing and make sure the update
 * from public repo does as well"*).
 *
 * A point step after the released 0.16.1, as 0.15.4.1 followed 0.15.4: a world on 0.16.1 stands at
 * `migrationVersion` 0.16.0.2 and runs it, and so does a fresh world (0.0.0). The release that
 * carries it is 0.16.2 or later.
 *
 * A creature a GM dragged out before the audit keeps its old block for good: combat reads the
 * stored `system.initiative` and `attacks[].bonus`, the Ward and Immune keys, the ability rows and
 * their descriptors. 307 of 14's creatures changed between release 0.16.1 and this pass (phase 1's
 * Wards, Immunities, types, attack rows and Boss kits, D-1780 to D-1789; the attribute pass,
 * D-1790 to D-1795; the size rule, D-1799). Every NPC in the world - world actors, the unlinked
 * tokens on every scene and the creatures in unlocked world packs (`walk.mjs`) - is read against
 * its PACK COPY, field by field, through `0.16.1.1-bestiary-audit-law.mjs#planCreature`:
 *
 * 1. **The old value is recorded, the new one is read off the pack.** The BEFORE table
 *    (`0.16.1.1-bestiary-audit.json`, generated by `tools/bestiary-audit-before.mjs` from release
 *    0.16.1's commit) holds each changed field's old value as a marker. A field is written only
 *    where the stored value is still that old value, and with the compiled pack's value.
 * 2. **A GM's rework is kept, field by field.** A field equal to neither is the GM's: kept and
 *    logged. A row list is judged row by row by name, a renamed row by its old name; a spent use
 *    is play and survives a restamp.
 * 3. **A creature is found** by the bestiary entry it was dragged from (`_stats.compendiumSource`),
 *    else by its name, else by its bond's `entryName`, so a swarm, a bound or raised creature, an
 *    unlinked token and an unlocked world pack's copy all take the same rule. A creature found by
 *    none is not one of the 307 (or a GM renamed it and it records no source): left, and counted.
 * 4. **A bound creature's Initiative is its owner's** (D-643), so its stored number is left.
 *
 * **A PACK BUILT BEFORE THE AUDIT WARNS AND STAMPS NOTHING** (0.13.1's and 0.16.0.1's shape): the
 * chain runs this as soon as the code is present, and a pass over an old pack would write nothing
 * new and mark the world past this version. `runMigrations` has already told the GM to back the
 * world up; every document touched is logged by `walkWorld`, and a second run writes nothing.
 */

import BEFORE from "./0.16.1.1-bestiary-audit.json" with { type: "json" };
import { BESTIARY_PACK, bestiaryEntryId, entryFor, initiativeDerived, missingSentinels, planCreature } from "./0.16.1.1-bestiary-audit-law.mjs";
import { packSystems, rawSystem, walkWorld } from "./walk.mjs";

export { BEFORE };

/** The migration's version, as the chain names it. */
export const VERSION = "0.16.1.1";

/** Where a stored creature says it was dragged from: core's record, or the flag before it. */
export function sourceOf(doc) {
  const source = doc?._source ?? {};
  return source._stats?.compendiumSource ?? doc?._stats?.compendiumSource ?? source.flags?.core?.sourceId ?? null;
}

/** The stored flags of a creature, a token's merged with its base. */
function flagsOf(doc) {
  return doc?._source?.flags ?? doc?.flags ?? null;
}

export async function migrate(log = console.log, table = BEFORE) {
  const bestiary = await packSystems(BESTIARY_PACK);
  const missing = missingSentinels(bestiary.byName);
  if (missing.length) {
    console.warn(bestiary.byName.size
      ? `azeroth-rpg | ${VERSION}: ${BESTIARY_PACK} predates the 2026-11 bestiary audit (it lacks ${missing.join(", ")}), so no creature was restamped. `
        + `Run \`npm run packs:parse\` and \`npm run packs:build\`, restart the server, set \`migrationVersion\` back to 0.16.0.2 and reload.`
      : `azeroth-rpg | ${VERSION}: ${BESTIARY_PACK} is not available, so no creature was restamped.`);
    return 0;
  }
  const counts = { creatures: 0, fields: 0, kept: 0, unmatched: 0, derived: 0, unknown: 0 };
  const touched = await walkWorld({
    actor: doc => {
      if (doc.type !== "npc") return null;
      const source = sourceOf(doc);
      const flags = flagsOf(doc);
      const entryName = flags?.["azeroth-rpg"]?.bond?.entryName ?? null;
      const entry = entryFor({ name: doc.name, source, entryName }, table);
      if (!entry) {
        // Not one of the 307: an entry the audit left alone, a GM's own creature, or a copy a GM
        // renamed that records no source. Only the last two are counted.
        const known = bestiaryEntryId(source) || bestiary.byName.has(doc.name) || (entryName && bestiary.byName.has(entryName));
        if (!known) counts.unknown++;
        return null;
      }
      const plan = planCreature(rawSystem(doc), bestiary.byName.get(entry.name) ?? null, entry, { derivedInitiative: initiativeDerived(flags) });
      const where = `${doc.name} (${doc.uuid ?? doc.id})`;
      if (plan.written.length) log(`azeroth-rpg | ${VERSION}: ${where} takes the bestiary audit's ${entry.name}: ${plan.written.join(", ")}`);
      if (plan.kept.length) log(`azeroth-rpg | ${VERSION}: ${where} keeps its own ${plan.kept.join(", ")}: neither the old pack copy nor the new one`);
      if (plan.unmatched.length) log(`azeroth-rpg | ${VERSION}: ${where} holds no row to restamp for ${plan.unmatched.join(", ")}`);
      if (plan.skipped.length) log(`azeroth-rpg | ${VERSION}: ${where} keeps its Initiative: a bound creature acts on its owner's`);
      if (plan.update) counts.creatures++;
      counts.fields += plan.written.length;
      counts.kept += plan.kept.length;
      counts.unmatched += plan.unmatched.length;
      counts.derived += plan.skipped.length;
      return plan.update;
    }
  }, log);
  log(`azeroth-rpg | ${VERSION}: ${counts.creatures} creature(s) restamped, ${counts.fields} field(s) or row(s) written, `
    + `${counts.kept} kept as a GM's own, ${counts.unmatched} row(s) unmatched, ${counts.derived} derived Initiative(s) left, `
    + `${counts.unknown} creature(s) not found in the bestiary`);
  if ((counts.creatures || counts.kept) && globalThis.game?.i18n) {
    globalThis.ui?.notifications?.info(game.i18n.format("AZEROTH.Migration.BestiaryAudit", {
      creatures: counts.creatures, kept: counts.kept, unmatched: counts.unmatched
    }), { permanent: true });
  }
  return touched;
}
